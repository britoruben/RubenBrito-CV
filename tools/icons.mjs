/**
 * Returns an inline <svg>. Decorative by default (aria-hidden), since every
 * icon here sits next to its own text label.
 */
export function icon(name, extraClass = '') {
  const cls = extraClass ? `icon ${extraClass}` : 'icon';
  const common = `class="${cls}" viewBox="0 0 24 24" width="16" height="16" aria-hidden="true" focusable="false"`;
  if (OUTLINE[name]) {
    return `<svg ${common} fill="none" stroke="currentColor" stroke-width="1.8" `
      + `stroke-linecap="round" stroke-linejoin="round">${OUTLINE[name]}</svg>`;
  }
  if (FILLED[name]) {
    return `<svg ${common} fill="currentColor">${FILLED[name]}</svg>`;
  }
  throw new Error(`Unknown icon: ${name}`);
}

export const ICON_NAMES = [...Object.keys(OUTLINE), ...Object.keys(FILLED)];
